    $dsn = sprintf('mysql:host=%s;dbname=%s;charset=utf8mb4', $db['host'], $db['dbname']);
    $pdo = new PDO($dsn, $db['user'], $db['pass']);
    $pdo->setAttribute(PDO::ATTR_ERRMODE, PDO::ERRMODE_EXCEPTION);

    $pdo->exec("
        CREATE TABLE IF NOT EXISTS rengyam_tag_meanings (
            id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
            tag_name VARCHAR(120) NOT NULL UNIQUE,
            source_label VARCHAR(60) NOT NULL,
            short_description VARCHAR(500) NOT NULL,
            is_active TINYINT(1) NOT NULL DEFAULT 1,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
    ");

    $stmt = $pdo->prepare("
        INSERT INTO rengyam_tag_meanings (tag_name, source_label, short_description, is_active)
        VALUES (:tag_name, :source_label, :short_description, 1)
        ON DUPLICATE KEY UPDATE
            source_label = VALUES(source_label),
            short_description = VALUES(short_description),
            is_active = 1
    ");

    $count = 0;
    foreach ($seed as $row) {
        $stmt->execute([
            ':tag_name' => $row[0],
            ':source_label' => $row[1],
