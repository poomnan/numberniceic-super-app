    fun explain(tag: String): String {
        val clean = tag.trim()
        if (clean.isEmpty()) return "คำอธิบายไม่พร้อมใช้งาน"
        meanings[clean]?.let { return it }
        if (clean.startsWith("มหาสูญ")) {
            return "ดิถีที่โบราณจัดเป็นวันพลังลบ ควรหลีกเลี่ยงการเริ่มงานสำคัญ"
        }
        if (clean.startsWith("อายกรรมพลาย")) {
            return "ดิถีเตือนเรื่องผลกระทบและความเสียหาย ควรพิจารณาให้รอบคอบก่อนเริ่มงาน"
        }
        if (clean.startsWith("อัคนิโรธ")) {
            val topic = clean.substringAfter("(-", "").substringBefore(")").trim()
            return if (topic.isNotEmpty()) {
                "ข้อห้ามเฉพาะกิจกรรมเกี่ยวกับ \"$topic\" ในวันนี้ ควรหลีกเลี่ยงหรือลดความเสี่ยง"
            } else {
                "ข้อห้ามเฉพาะวันตามตำราโหร ควรหลีกเลี่ยงกิจกรรมที่มีความเสี่ยง"
            }
        }
        return "ฤกษ์นี้เป็นตัวชี้วัดเชิงตำรา ใช้ประกอบการตัดสินใจร่วมกับบริบทจริงของงาน"
    }
